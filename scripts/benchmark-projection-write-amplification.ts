#!/usr/bin/env bun
import { temporaryDatabase } from "../tests/test-database.mjs";
import { rebuildRegionScopes } from "../src/region-scope-aggregate.js";

const confirmation = "run-isolated-projection-write-benchmark";
const connectionString = process.env.POSTGRES_TEST_URL?.trim();
if (!connectionString)
  throw new Error("POSTGRES_TEST_URL must name an isolated test database");
const databaseName = new URL(connectionString).pathname.slice(1).toLowerCase();
if (!databaseName.includes("test") && !databaseName.includes("bench"))
  throw new Error("benchmark database name must contain test or bench");
if (process.env.POSTGRES_PROJECTION_BENCHMARK_CONFIRM !== confirmation)
  throw new Error(
    `POSTGRES_PROJECTION_BENCHMARK_CONFIRM must equal ${confirmation}`,
  );

const fixture = await temporaryDatabase("projection-write-benchmark-");
const database = fixture.database;
const now = 1_800_000_000_000;
const observerKey = "A".repeat(64);

async function walLsn() {
  return String(
    (await database.get("SELECT pg_current_wal_lsn()::text AS lsn")).lsn,
  );
}
async function walBytes(before, after) {
  return Number(
    (
      await database.get(
        "SELECT pg_wal_lsn_diff($1::pg_lsn, $2::pg_lsn)::bigint AS bytes",
        after,
        before,
      )
    ).bytes,
  );
}

try {
  await database.run(`
    CREATE TABLE projection_metric_private_benchmark(
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      observer_public_key text NOT NULL,
      received_at_ms bigint NOT NULL,
      metric_name text NOT NULL,
      numeric_value double precision NOT NULL
    );
    CREATE INDEX projection_metric_private_received_benchmark
      ON projection_metric_private_benchmark(observer_public_key, metric_name, received_at_ms DESC, id DESC);
    CREATE TABLE projection_metric_public_benchmark(
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      private_id bigint NOT NULL UNIQUE,
      observer_public_key text NOT NULL,
      received_at_ms bigint NOT NULL,
      metric_name text NOT NULL,
      numeric_value double precision NOT NULL
    );
    CREATE INDEX projection_metric_public_received_benchmark
      ON projection_metric_public_benchmark(observer_public_key, metric_name, received_at_ms DESC, id DESC);
    CREATE FUNCTION benchmark_project_metric() RETURNS trigger LANGUAGE plpgsql AS $$
    BEGIN
      INSERT INTO projection_metric_public_benchmark(
        private_id, observer_public_key, received_at_ms, metric_name, numeric_value
      ) VALUES (
        NEW.id, NEW.observer_public_key, NEW.received_at_ms, NEW.metric_name, NEW.numeric_value
      );
      RETURN NEW;
    END $$;
    CREATE TRIGGER benchmark_project_metric_trigger
      AFTER INSERT ON projection_metric_private_benchmark
      FOR EACH ROW EXECUTE FUNCTION benchmark_project_metric();
  `);
  const legacyBefore = await walLsn();
  const legacyStarted = performance.now();
  await database.run(
    `INSERT INTO projection_metric_private_benchmark(
       observer_public_key, received_at_ms, metric_name, numeric_value
     ) SELECT $1, $2 + value, 'metric_' || value::text, value::double precision
       FROM generate_series(1,1000) value`,
    observerKey,
    now,
  );
  const legacyMs = performance.now() - legacyStarted;
  const legacyAfter = await walLsn();

  await database.run(
    `INSERT INTO observers(public_key, first_seen_at_ms, last_seen_at_ms, created_at_ms, updated_at_ms)
     VALUES ($1,$2,$2,$2,$2)`,
    observerKey,
    now,
  );
  const observer = await database.get(
    "SELECT id FROM observers WHERE public_key = $1",
    observerKey,
  );
  await database.run(
    `INSERT INTO mqtt_event_provenance(event_id, topic, iata, observer_public_key, payload_sha256,
       payload_size_bytes, qos, retain, dup, received_at_ms, parser_name, parser_version,
       collector_instance_id, created_at_ms)
     VALUES (1,$1,'STO',$2,$3,2,0,false,false,$4,'bench','1','bench',$4)`,
    `meshcore/STO/${observerKey}/status`,
    observerKey,
    "f".repeat(64),
    now,
  );
  const beforeMetric = await walLsn();
  const metricStarted = performance.now();
  await database.run(
    `INSERT INTO observer_metrics(observer_id, mqtt_event_id, received_at_ms, metric_name, numeric_value)
     SELECT $1, 1, $2 + value, 'metric_' || value::text, value::double precision
     FROM generate_series(1,1000) value`,
    observer.id,
    now,
  );
  const metricMs = performance.now() - metricStarted;
  const afterMetric = await walLsn();

  const queryRounds = 100;
  const legacyQueryStarted = performance.now();
  for (let index = 0; index < queryRounds; index += 1) {
    await database.all(
      `SELECT id, observer_public_key, received_at_ms, metric_name, numeric_value
       FROM projection_metric_public_benchmark
       WHERE observer_public_key=$1 AND metric_name=$2
       ORDER BY received_at_ms DESC, id DESC LIMIT 100`,
      observerKey,
      "metric_500",
    );
  }
  const legacyQueryMs = performance.now() - legacyQueryStarted;
  const viewQueryStarted = performance.now();
  for (let index = 0; index < queryRounds; index += 1) {
    await database.all(
      `SELECT id, observer_public_key, received_at_ms, metric_name, numeric_value
       FROM meshcore_public.observer_metrics
       WHERE observer_public_key=$1 AND metric_name=$2
       ORDER BY received_at_ms DESC, id DESC LIMIT 100`,
      observerKey,
      "metric_500",
    );
  }
  const viewQueryMs = performance.now() - viewQueryStarted;

  await database.run(
    `INSERT INTO meshcore_public.region_scopes(region, name, first_seen_at_ms, last_seen_at_ms, observation_count)
     VALUES ('STO','Stockholm',$1,$1,1)
     ON CONFLICT(region) DO UPDATE SET first_seen_at_ms=$1,last_seen_at_ms=$1,observation_count=1`,
    now,
  );
  await database.transaction((transaction) =>
    rebuildRegionScopes(transaction, ["STO"]),
  )();
  const regionXminBefore = await database.get(
    "SELECT xmin::text AS xmin FROM meshcore_public.region_scopes WHERE region='STO'",
  );
  const beforeRegions = await walLsn();
  const regionStarted = performance.now();
  for (let index = 0; index < 250; index += 1) {
    await database.transaction((transaction) =>
      rebuildRegionScopes(transaction, ["STO"]),
    )();
  }
  const regionMs = performance.now() - regionStarted;
  const afterRegions = await walLsn();
  const regionXminAfter = await database.get(
    "SELECT xmin::text AS xmin FROM meshcore_public.region_scopes WHERE region='STO'",
  );

  const publicMetricRelation = await database.get(
    `SELECT cls.relkind,
            CASE WHEN cls.relkind IN ('r','m','p') THEN pg_total_relation_size(cls.oid) ELSE 0 END AS bytes
     FROM pg_class cls JOIN pg_namespace ns ON ns.oid=cls.relnamespace
     WHERE ns.nspname='meshcore_public' AND cls.relname='observer_metrics'`,
  );
  const metricTriggers = await database.all(
    `SELECT trigger_name FROM information_schema.triggers
     WHERE event_object_schema='meshcore_private' AND event_object_table='observer_metrics'`,
  );
  const relationSizes = await database.all(
    `SELECT ns.nspname AS schema, cls.relname,
            pg_relation_size(cls.oid) AS heap_bytes,
            pg_indexes_size(cls.oid) AS index_bytes,
            pg_total_relation_size(cls.oid) AS total_bytes
     FROM pg_class cls JOIN pg_namespace ns ON ns.oid=cls.relnamespace
     WHERE ns.nspname IN ('meshcore_private','meshcore_public')
       AND cls.relname IN ('observer_metrics','packet_observations','packet_path_hops','packets')
       AND cls.relkind IN ('r','p')
     ORDER BY pg_total_relation_size(cls.oid) DESC`,
  );
  const benchmarkSizes = await database.all(
    `SELECT relname,
            pg_relation_size(oid) AS heap_bytes,
            pg_indexes_size(oid) AS index_bytes,
            pg_total_relation_size(oid) AS total_bytes
     FROM pg_class
     WHERE relname IN ('projection_metric_private_benchmark','projection_metric_public_benchmark')
     ORDER BY relname`,
  );

  console.log(
    JSON.stringify(
      {
        legacyTriggerDuplicate: {
          insertedSourceRows: 1000,
          insertedPhysicalFactRows: 2000,
          durationMs: legacyMs,
          walBytes: await walBytes(legacyBefore, legacyAfter),
          queryRounds,
          queryDurationMs: legacyQueryMs,
          relations: benchmarkSizes,
        },
        observerMetrics: {
          insertedRows: 1000,
          durationMs: metricMs,
          walBytes: await walBytes(beforeMetric, afterMetric),
          queryRounds,
          queryDurationMs: viewQueryMs,
          publicRelationKind: publicMetricRelation.relkind,
          publicPhysicalBytes: Number(publicMetricRelation.bytes),
          projectionTriggers: metricTriggers.length,
          physicalDuplicateEliminated:
            publicMetricRelation.relkind === "v" &&
            Number(publicMetricRelation.bytes) === 0 &&
            metricTriggers.length === 0,
        },
        regionScopesNoOpRebuild: {
          iterations: 250,
          durationMs: regionMs,
          walBytes: await walBytes(beforeRegions, afterRegions),
          rowVersionChanged: regionXminBefore.xmin !== regionXminAfter.xmin,
        },
        relationSizes,
      },
      null,
      2,
    ),
  );
} finally {
  await database
    .run(
      "DROP TABLE IF EXISTS projection_metric_private_benchmark, projection_metric_public_benchmark CASCADE; DROP FUNCTION IF EXISTS benchmark_project_metric()",
    )
    .catch(() => undefined);
  await fixture.cleanup();
}
