#!/usr/bin/env bun
import { temporaryDatabase } from "../tests/test-database.mjs";

const confirmation = "run-isolated-observer-metrics-benchmark";
const connectionString = process.env.POSTGRES_TEST_URL?.trim();
if (!connectionString)
  throw new Error("POSTGRES_TEST_URL must name an isolated test database");
const databaseName = new URL(connectionString).pathname.slice(1).toLowerCase();
if (!databaseName.includes("test") && !databaseName.includes("bench"))
  throw new Error("benchmark database name must contain test or bench");
if (process.env.POSTGRES_TIMESCALE_BENCHMARK_CONFIRM !== confirmation)
  throw new Error(
    `POSTGRES_TIMESCALE_BENCHMARK_CONFIRM must equal ${confirmation}`,
  );

const fixture = await temporaryDatabase("observer-metrics-benchmark-");
const database = fixture.database;
const baseMs = 1_700_000_000_000;
const rows = 200_000;

async function walLsn() {
  return String(
    (await database.get("SELECT pg_current_wal_lsn()::text AS lsn")).lsn,
  );
}

async function walBytes(before, after) {
  return Number(
    (
      await database.get(
        "SELECT pg_wal_lsn_diff($1::pg_lsn, $2::pg_lsn)::bigint AS bytes",
        after,
        before,
      )
    ).bytes,
  );
}

async function measureInsert(layout) {
  const before = await walLsn();
  const startedAt = performance.now();
  await database.run(
    layout === "plain"
      ? `INSERT INTO observer_metrics_plain_benchmark(observer_id, received_at_ms, metric_name, numeric_value)
         SELECT (value % 500)::bigint, $1 + value::bigint * 30000,
                CASE value % 3 WHEN 0 THEN 'battery' WHEN 1 THEN 'uptime' ELSE 'queue' END,
                value::double precision
         FROM generate_series(1, $2) AS value`
      : `INSERT INTO observer_metrics_ts_benchmark(observer_id, received_at_ms, metric_name, numeric_value)
         SELECT (value % 500)::bigint, $1 + value::bigint * 30000,
                CASE value % 3 WHEN 0 THEN 'battery' WHEN 1 THEN 'uptime' ELSE 'queue' END,
                value::double precision
         FROM generate_series(1, $2) AS value`,
    baseMs,
    rows,
  );
  const durationMs = performance.now() - startedAt;
  const after = await walLsn();
  return { durationMs, walBytes: await walBytes(before, after) };
}

async function measureRangeQuery(layout) {
  const startedAt = performance.now();
  const result = await database.get(
    layout === "plain"
      ? `SELECT count(*)::int AS count, avg(numeric_value) AS average
         FROM observer_metrics_plain_benchmark WHERE received_at_ms >= $1`
      : `SELECT count(*)::int AS count, avg(numeric_value) AS average
         FROM observer_metrics_ts_benchmark WHERE received_at_ms >= $1`,
    baseMs + rows * 30_000 - 86_400_000,
  );
  return { durationMs: performance.now() - startedAt, ...result };
}

try {
  await database.run(`
    CREATE TABLE observer_metrics_plain_benchmark (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      observer_id bigint NOT NULL,
      received_at_ms bigint NOT NULL,
      metric_name text NOT NULL,
      numeric_value double precision NOT NULL
    );
    CREATE INDEX observer_metrics_plain_received_benchmark
      ON observer_metrics_plain_benchmark(received_at_ms DESC);
    CREATE TABLE observer_metrics_ts_benchmark (
      id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
      observer_id bigint NOT NULL,
      received_at_ms bigint NOT NULL,
      metric_name text NOT NULL,
      numeric_value double precision NOT NULL,
      PRIMARY KEY(id, received_at_ms)
    );
    SELECT public.create_hypertable(
      'meshcore_private.observer_metrics_ts_benchmark'::regclass,
      public.by_range('received_at_ms'::name, 604800000::bigint)
    );
  `);
  const plainInsert = await measureInsert("plain");
  const timescaleInsert = await measureInsert("timescale");
  const plainQuery = await measureRangeQuery("plain");
  const timescaleQuery = await measureRangeQuery("timescale");
  const sizes = await database.get(
    `SELECT
       pg_total_relation_size('meshcore_private.observer_metrics_plain_benchmark')::bigint AS plain_bytes,
       public.hypertable_size('meshcore_private.observer_metrics_ts_benchmark'::regclass)::bigint AS timescale_bytes`,
  );

  const cutoff = baseMs + rows * 15_000;
  const plainRetentionStartedAt = performance.now();
  await database.run(
    "DELETE FROM observer_metrics_plain_benchmark WHERE received_at_ms < $1",
    cutoff,
  );
  const plainRetentionMs = performance.now() - plainRetentionStartedAt;
  const timescaleRetentionStartedAt = performance.now();
  await database.all(
    "SELECT public.drop_chunks('meshcore_private.observer_metrics_ts_benchmark'::regclass, older_than => $1::bigint)",
    cutoff,
  );
  const timescaleRetentionMs = performance.now() - timescaleRetentionStartedAt;

  console.log(
    JSON.stringify(
      {
        rowsPerLayout: rows,
        chunkIntervalMs: 604_800_000,
        plain: {
          insert: plainInsert,
          rangeQuery: plainQuery,
          bytes: Number(sizes.plain_bytes),
          retentionMs: plainRetentionMs,
        },
        timescaleRowstore: {
          insert: timescaleInsert,
          rangeQuery: timescaleQuery,
          bytes: Number(sizes.timescale_bytes),
          retentionMs: timescaleRetentionMs,
        },
        columnstore: {
          availableFunctions: await database.all(
            `SELECT proname FROM pg_proc
             WHERE proname IN ('add_columnstore_policy', 'add_compression_policy', 'convert_to_columnstore')
             ORDER BY proname`,
          ),
          decision:
            "evaluate only for chunks older than the reprocessing window; rowstore remains required for mutable recent history",
        },
      },
      null,
      2,
    ),
  );
} finally {
  await database
    .run(
      "DROP TABLE IF EXISTS observer_metrics_plain_benchmark, observer_metrics_ts_benchmark CASCADE",
    )
    .catch(() => undefined);
  await fixture.cleanup();
}
