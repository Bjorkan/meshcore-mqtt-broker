#!/usr/bin/env bun
import { temporaryDatabase } from "../tests/test-database.mjs";

const confirmation = "run-isolated-retention-layout-benchmark";
const connectionString = process.env.POSTGRES_TEST_URL?.trim();
if (!connectionString)
  throw new Error("POSTGRES_TEST_URL must name an isolated test database");
const databaseName = new URL(connectionString).pathname.slice(1).toLowerCase();
if (!databaseName.includes("test") && !databaseName.includes("bench"))
  throw new Error("benchmark database name must contain test or bench");
if (process.env.POSTGRES_RETENTION_BENCHMARK_CONFIRM !== confirmation)
  throw new Error(
    `POSTGRES_RETENTION_BENCHMARK_CONFIRM must equal ${confirmation}`,
  );

const requestedRows = Number(
  process.env.POSTGRES_RETENTION_BENCHMARK_ROWS ?? "1000000",
);
if (
  !Number.isSafeInteger(requestedRows) ||
  requestedRows < 1_000_000 ||
  requestedRows > 10_000_000
)
  throw new Error(
    "POSTGRES_RETENTION_BENCHMARK_ROWS must be an integer from 1000000 to 10000000",
  );

const fixture = await temporaryDatabase("retention-layout-benchmark-");
const database = fixture.database;
const baseMs = 1_700_000_000_000;
const cutoff = baseMs + Math.floor(requestedRows / 2) * 1_000;

async function walLsn() {
  return String(
    (await database.get("SELECT pg_current_wal_lsn()::text AS lsn")).lsn,
  );
}
async function walBytes(before, after) {
  return Number(
    (
      await database.get(
        "SELECT pg_wal_lsn_diff($1::pg_lsn, $2::pg_lsn)::bigint AS bytes",
        after,
        before,
      )
    ).bytes,
  );
}
async function seed(table) {
  await database.run(
    `INSERT INTO ${table}(received_at_ms, payload)
     SELECT $1 + value::bigint * 1000, repeat('x', 96)
     FROM generate_series(1, $2) value`,
    baseMs,
    requestedRows,
  );
}

try {
  await database.run(`
    CREATE TABLE retention_plain_benchmark(
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      received_at_ms bigint NOT NULL,
      payload text NOT NULL
    );
    CREATE INDEX retention_plain_received ON retention_plain_benchmark(received_at_ms, id);
    CREATE TABLE retention_ts_benchmark(
      id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
      received_at_ms bigint NOT NULL,
      payload text NOT NULL,
      PRIMARY KEY(id, received_at_ms)
    );
    SELECT public.create_hypertable(
      'meshcore_private.retention_ts_benchmark'::regclass,
      public.by_range('received_at_ms'::name, 86400000::bigint)
    );
  `);
  await seed("retention_plain_benchmark");
  await seed("retention_ts_benchmark");

  const plainBefore = await walLsn();
  const plainStarted = performance.now();
  let plainDeleted = 0;
  for (;;) {
    const rows = await database.all(
      `DELETE FROM retention_plain_benchmark
       WHERE id IN (
         SELECT id FROM retention_plain_benchmark
         WHERE received_at_ms < $1 ORDER BY received_at_ms, id LIMIT 10000
       ) RETURNING id`,
      cutoff,
    );
    plainDeleted += rows.length;
    if (rows.length < 10_000) break;
  }
  const plainMs = performance.now() - plainStarted;
  const plainAfter = await walLsn();

  const tsBefore = await walLsn();
  const tsStarted = performance.now();
  const droppedChunks = await database.all(
    "SELECT public.drop_chunks('meshcore_private.retention_ts_benchmark'::regclass, older_than => $1::bigint)::text AS chunk",
    cutoff,
  );
  const tsMs = performance.now() - tsStarted;
  const tsAfter = await walLsn();

  console.log(
    JSON.stringify(
      {
        rowsPerLayout: requestedRows,
        cutoff,
        batchedDelete: {
          deletedRows: plainDeleted,
          durationMs: plainMs,
          walBytes: await walBytes(plainBefore, plainAfter),
        },
        timescaleChunkExpiry: {
          droppedChunks: droppedChunks.length,
          durationMs: tsMs,
          walBytes: await walBytes(tsBefore, tsAfter),
        },
      },
      null,
      2,
    ),
  );
} finally {
  await database
    .run(
      "DROP TABLE IF EXISTS retention_plain_benchmark, retention_ts_benchmark CASCADE",
    )
    .catch(() => undefined);
  await fixture.cleanup();
}
